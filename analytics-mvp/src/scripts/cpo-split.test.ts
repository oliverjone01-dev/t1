import { describe, it, expect } from "vitest";
import { splitCpo } from "./cpo-split.js";

describe("реклама за заказ по отправлениям (Иван 30.09, вариант 1)", () => {
  it("0172335655-0037: вся сумма на отправление, у артикула которого в день заказа был CPO", () => {
    const r = splitCpo({ "0172335655-0037": 1393 }, [
      { order: "0172335655-0037-1", d: "2026-07-14", sku: "3564022917" },
      { order: "0172335655-0037-2", d: "2026-07-14", sku: "3563989798" },
    ], { "2026-07-14|3564022917": 1393 });
    expect(r).toEqual({ "0172335655-0037-1": 1393 });
  });
  it("не понять по артикулу - поровну, сумма не задваивается", () => {
    const r = splitCpo({ "78782234-0454": 9316 }, [
      { order: "78782234-0454-1", d: "2026-07-01", sku: "A" },
      { order: "78782234-0454-3", d: "2026-07-01", sku: "A" },
    ], { "2026-07-01|A": 9316 });
    expect(r).toEqual({ "78782234-0454-1": 4658, "78782234-0454-3": 4658 });
  });
  it("в суточном отчёте ничего - поровну на все, остаток на последнее; отменённое не берётся", () => {
    const r = splitCpo({ "1-2": 101 }, [
      { order: "1-2-1", d: "2026-07-01", sku: "A" },
      { order: "1-2-2", d: "2026-07-01", sku: "B", status: "cancelled" },
      { order: "1-2-3", d: "2026-07-01", sku: "C" },
    ], {});
    expect(r).toEqual({ "1-2-1": 50, "1-2-3": 51 });
  });
  it("одно отправление - вся сумма", () => {
    expect(splitCpo({ "5-6": 700 }, [{ order: "5-6-1", d: "2026-07-01", sku: "A" }], {})).toEqual({ "5-6-1": 700 });
  });
});
