// Гейт накопительного факт-слоя Маркета (пробел, который пропустил потерю 4 898 строк реестра).
//
// Существующий дельта-гейт сторожит ТОЛЬКО три 30-дневные производные (skus_live_30d, pnl_30d,
// pnl_sku_30d). Накопительные файлы - заказы, реестр взаиморасчётов, реализация, показы - копятся
// за девять месяцев и не сторожатся ничем. Живой факт 2026-09-07: чистка реестра по неверному ключу
// снесла 4 898 строк и 9 354 730 ₽ за 2026-03..2026-06, все 30-дневные производные при этом не
// шелохнулись, и прогон завершился зелёным.
//
// Здесь сторожим то, что копится: число строк и сумму по месяцам. Накопительный файл имеет право
// расти и уточняться, но не имеет права терять уже собранный месяц.
// Для ЗНАКОВОГО реестра сумму надо брать по модулю (--abs). Живой факт 2026-09-16: гейт остановил
// прогон на 1023124/2026-09 («сумма amount была 387 595, стала 309 953»), хотя не потерялось ни
// строки - про строки он как раз не ругался. В netting.ndjson «Начисление» плюс, «Списание» минус,
// и месячная сумма это САЛЬДО: 387 595 ₽ при обороте 3 002 575 ₽, то есть 12.9%. Один день двигает
// сальдо в среднем на 67 229 ₽, а максимум за сентябрь - 297 366 ₽. Просадка, на которую ругнулся
// гейт, - 77 642 ₽, меньше медианного дня: это просто добор 15 сентября, где списаний больше начислений.
// Порог 10% от сальдо - это 1.3% от оборота, то есть гейт срабатывал на шуме. По модулю всё честно:
// потеря строк ВСЕГДА уменьшает оборот, а задвоение его растит, поэтому --abs не ослабляет защиту,
// а делает её применимой к знаковым файлам.
// Запуск: tsx validate-facts.ts <файл.ndjson> <прошлый.ndjson|""> [--month-key=d|date|ym] [--sum=amount] [--abs]
import { readFileSync, existsSync } from "node:fs";
import { FLOOR_DEFAULT } from "./common.js";

// Порог просадки месяца. ФЕНИКС 2026-09-07: Number('abc') = NaN, и тогда ВСЕ сравнения давали false -
// гейт печатал «потерь нет» при минус половине; а значение 1 отключало его целиком. Значение вне
// разумного диапазона - это ошибка настройки, и она обязана ронять прогон, а не молча снимать защиту.
function threshold(raw: string | undefined, name: string, def: number, max: number): number {
  if (raw === undefined || raw === "") return def;
  const v = Number(raw);
  if (!Number.isFinite(v) || v <= 0 || v > max) {
    console.error(`FACTS INVALID: ${name}="${raw}" - не число в диапазоне (0, ${max}]. Гейт не запускается: неверная настройка не должна выглядеть как «потерь нет».`);
    process.exit(1);
  }
  return v;
}
const DROP = threshold(process.env.YM_FACTS_DROP_GATE, "YM_FACTS_DROP_GATE", 0.1, 0.5);  // просадка месяца
// Потолок роста закрытого месяца. Верхняя граница 2.0, а не 20: значение 20 проходило валидацию и
// на месяце x2 давало «аномалий нет» - легальный выключатель детектора задвоения (ФЕНИКС iter3).
// Верхняя граница 0.9, а не 2: при 2 ровное удвоение (+100%) проходило под порогом, то есть
// разрешённое значение оставалось выключателем детектора - просто более узким (ФЕНИКС iter4).
const GROW = threshold(process.env.YM_FACTS_GROW_GATE, "YM_FACTS_GROW_GATE", 0.25, 0.9); // рост ЗАКРЫТОГО месяца

// Бэкфилл вглубь. Прогон с опущенным YM_FLOOR впервые запрашивает месяцы НИЖЕ дефолтного
// пола, и там рост закрытого месяца - ровно то, ради чего прогон запущен, а не задвоение.
// Живой факт 2026-09-21: прогон с YM_FLOOR=2026-01-01 встал на netting.ndjson, где январь
// вырос 201 -> 524 и 335 -> 1061. Раньше в январе лежали только строки, залетевшие в окно
// февраля; теперь месяц собран целиком.
// Ослабляется ТОЛЬКО потолок роста и ТОЛЬКО ниже дефолтного пола. Детектор ПОТЕРИ не
// трогается нигде и никогда: потеря не бывает ожидаемой ни на каком прогоне.
export function backfillBelow(ymFloor: string | undefined, floorDefault = FLOOR_DEFAULT): string {
  const f = String(ymFloor || "").trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(f)) return "";   // пол не задан или задан мусором - обычный прогон
  return f < floorDefault ? floorDefault.slice(0, 7) : "";
}
const BACKFILL_BELOW = backfillBelow(process.env.YM_FLOOR);

function rows(p: string): any[] {
  if (!p || !existsSync(p)) return [];
  return readFileSync(p, "utf-8").split("\n").filter((l) => l.trim()).map((l) => {
    try { return JSON.parse(l); } catch { return null; }
  }).filter(Boolean);
}

function main() {
  const [file, prevFile] = [process.argv[2]!, process.argv[3] || ""];
  const arg = (n: string, d: string) => (process.argv.find((a) => a.startsWith(`--${n}=`)) || `--${n}=${d}`).split("=")[1]!;
  const mk = arg("month-key", "d"), sumK = arg("sum", "");
  const abs = process.argv.includes("--abs");
  const val = (r: any) => { const v = Number(r[sumK]) || 0; return abs ? Math.abs(v) : v; };
  const byBizEarly = process.argv.includes("--by=business");
  // Добор НОВОГО ИНСТРУМЕНТА в закрытый месяц. Живой факт 14.10.2026 (прогон 38562814961): продьюсер
  // отчётов продвижения впервые дошёл до февраля мебели по показам и полкам (в состоянии за февраль
  // был только буст), строк за месяц стало 3 вместо 1, и потолок роста закрытого месяца остановил
  // прогон как «задвоение». Состояние продьюсера не закоммитилось, и каждый следующий прогон вставал
  // бы на том же месте: реестр, баллы и акт перестали обновляться. Задвоение и добор различаются
  // ключом строки: задвоение кладёт вторую строку под УЖЕ СОБРАННЫЙ ключ, добор приносит ключ,
  // которого раньше не было. Поэтому с --new-key=<поле> рост закрытого месяца проверяется по
  // ключам кабинет/месяц/<поле>: по ключам, что были в прошлом снимке, те же пороги, что и раньше;
  // ключ, которого не было, добавлять можно, но только со значением поля, которое файл уже знает
  // (buost/shows/shelf): новое имя инструмента - это смена схемы продьюсера, а не добор.
  // Детектор потери не трогается. Файлы без флага проверяются байт в байт как раньше.
  const newKey = arg("new-key", "");
  const cur = rows(file);
  const prev = rows(prevFile);
  if (newKey && cur.some((r) => r[newKey] == null || r[newKey] === "")) {
    console.error(`FACTS INVALID: ${file} - --new-key=${newKey}, но у части строк поля ${newKey} нет: без него добор не отличить от задвоения, гейт не запускается`);
    process.exit(1);
  }
  const knownKeyVals = new Set(prev.map((r) => String(r[newKey])));
  // Сколько строк один ключ (значение поля) занимал в прошлом снимке внутри одного кабинета/месяца,
  // максимум по всем месяцам. Новый ключ в закрытом месяце не может быть толще, чем тот же инструмент
  // в любом другом месяце: у promo это ровно одна строка, две строки «показы» за февраль - задвоение,
  // а не добор (Codex P2 на PR #475).
  const knownKeyMax = new Map<string, number>();
  // Источника может не быть вовсе. Отчёта по баллам Маркета в Partner API не существует (все 22
  // метода генерации выписаны из OpenAPI-спецификации, вызовы united-bonuses / bonuses /
  // united-marketplace-bonuses отдают 404), поэтому bonuses_monthly.ndjson не появляется, и гейт
  // ронял прогон на «пуст или нечитаем» - при том, что ронять тут нечего.
  // Но «файла нет» законно ТОЛЬКО когда его не было и раньше: исчезновение собранного файла - это
  // ровно та потеря, ради которой гейт и стоит.
  if (!existsSync(file)) {
    if (prev.length) { console.error(`FACTS INVALID: ${file} исчез, а в прошлом снимке было ${prev.length} строк`); process.exit(1); }
    console.log(`facts-gate ${file}: источник не собран и раньше не собирался - сторожить нечего`);
    return;
  }
  if (!cur.length) { console.error(`FACTS INVALID: ${file} пуст или нечитаем`); process.exit(1); }
  if (!prev.length) { console.log(`facts-gate ${file}: строк ${cur.length}, прошлого снимка нет - сравнивать не с чем`); return; }

  // Ключ агрегации - пара (кабинет, месяц), если файл её несёт. Чистка в продьюсере идёт по паре,
  // и гейт по одному месяцу пропускал потерю целого кабинета: у 1023124/2026-06 доля в месяце 19.2%,
  // то есть минус половина кабинета - это минус 9.6% месяца, под порогом 10%.
  const byBiz = byBizEarly;
  // Потолок роста включаем только там, где есть ключ кабинета. У реализации его нет, повторный
  // разбор сливается по SKU и не меняет числа строк, поэтому прирост суммы неотличим от законного
  // добора УПД: живой случай - 2026-08, шесть магазинов из семи ждут УПД, их приход законно даст
  // больше 25%. Для реализации задвоение снято в источнике (пересбор вместо переоткрытия).
  const growOn = byBiz;
  // Строки-агрегаты (окно целиком одной датой) заменяются следующим окном целиком, поэтому по
  // МЕСЯЦАМ их сравнивать нельзя: смена окна давала бы «потерю» каждый прогон. Но выбрасывать их
  // из сравнения было хуже: сегодня 4504 строки из 4504 в sku_views несут этот флаг, и гейт
  // сравнивал пустоту с пустотой - потеря 90% строк давала «аномалий нет» (ФЕНИКС iter4, и мой
  // собственный тест закреплял эту дыру зелёной). Агрегаты сравниваем ОТДЕЛЬНЫМ ведром «окно
  // целиком»: месяц там ни при чём, а объём и сумма сторожатся как у всех.
  const AGG_BUCKET = "агрегат окна";
  type Bucket = { n: number; s: number; k: Record<string, { n: number; s: number }> };
  const agg = (rs: any[]) => {
    const m: Record<string, Bucket> = {};
    for (const r of rs) {
      if (r.aggregate) {
        const k = byBizEarly && r.business ? `${r.business}/${AGG_BUCKET}` : AGG_BUCKET;
        const b = (m[k] ||= { n: 0, s: 0, k: {} });
        b.n++; if (sumK) b.s += val(r);
        continue;
      }
      const mon = String(r[mk] || "").slice(0, 7); if (!mon) continue;
      const key = byBiz && r.business ? `${r.business}/${mon}` : mon;
      const b = (m[key] ||= { n: 0, s: 0, k: {} });
      b.n++; if (sumK) b.s += val(r);
      if (newKey) { const kb = (b.k[String(r[newKey])] ||= { n: 0, s: 0 }); kb.n++; if (sumK) kb.s += val(r); }
    }
    return m;
  };
  // Рост закрытого месяца при --new-key: по старым ключам те же пороги, новые ключи - только со
  // знакомым значением поля. Возвращает причину отказа или "" (рост объяснён добором).
  const growByKeys = (mth: string, p: Bucket, c: Bucket): string => {
    for (const [kv, pk] of Object.entries(p.k)) {
      const ck = c.k[kv] || { n: 0, s: 0 };
      // Старый ключ не имеет права ни пропасть, ни похудеть: добор соседних инструментов может держать
      // месяц целиком выше порога потери, пока буст из него исчез (Codex P2 на PR #475).
      if (ck.n < pk.n * (1 - DROP)) return `${mth}/${kv}: строк было ${pk.n}, стало ${ck.n} (старый ключ потерян за добором соседей)`;
      if (sumK && Math.abs(pk.s) > 1 && Math.abs(ck.s) < Math.abs(pk.s) * (1 - DROP)) return `${mth}/${kv}: сумма ${sumK} была ${Math.round(pk.s)}, стала ${Math.round(ck.s)} (старый ключ похудел за добором соседей)`;
      if (ck.n >= pk.n * (1 + GROW)) return `${mth}/${kv}: строк было ${pk.n}, стало ${ck.n} (закрытый ключ вырос - задвоение)`;
      if (sumK && Math.abs(pk.s) > 1 && Math.abs(ck.s) >= Math.abs(pk.s) * (1 + GROW)) return `${mth}/${kv}: сумма ${sumK} была ${Math.round(pk.s)}, стала ${Math.round(ck.s)} (закрытый ключ вырос - задвоение)`;
    }
    const fresh = Object.keys(c.k).filter((kv) => !(kv in p.k));
    const alien = fresh.filter((kv) => !knownKeyVals.has(kv));
    if (alien.length) return `${mth}: новое значение ${newKey}=${alien.join(", ")}, которого прошлый снимок не знал ни в одном месяце - смена схемы, а не добор`;
    const fat = fresh.filter((kv) => c.k[kv]!.n > (knownKeyMax.get(kv) || 1));
    if (fat.length) return `${mth}: новый ключ ${fat.map((kv) => `${kv} (${c.k[kv]!.n} строк при максимуме ${knownKeyMax.get(kv) || 1})`).join(", ")} - задвоение внутри добора`;
    console.log(`facts-gate ${file}: ${mth} - добор ${newKey}=${fresh.join(", ")} в закрытый месяц, по старым ключам роста нет`);
    return "";
  };
  const a = agg(prev), b = agg(cur);
  if (newKey) for (const bk of Object.values(a)) for (const [kv, x] of Object.entries(bk.k)) knownKeyMax.set(kv, Math.max(knownKeyMax.get(kv) || 0, x.n));
  // Самый свежий месяц базового снимка законно добирается прогон за прогоном (текущий месяц ещё
  // идёт), поэтому потолок роста к нему не применяем - иначе гейт кричал бы каждый день. К закрытым
  // месяцам применяем: там рост означает, что разбор сложился поверх уже накопленного.
  const monthOf = (k: string) => k.slice(-7);
  // Ведро агрегатов исключаем ПО ИМЕНИ: его хвост «ат окна» сортируется после «2026-10» и объявлял
  // текущий месяц закрытым (сбор Маркета падал 03.10-11.10, E076). Фильтр по формату вместо имени
  // открывал другую дыру: месяц в чужом формате (2026/08, 202608) давал пустой newest, и потолок
  // роста молча снимался со всех месяцев (ФЕНИКС G8). Поэтому чужой формат - отказ, а не пропуск.
  const isAgg = (k: string) => k === AGG_BUCKET || k.endsWith(`/${AGG_BUCKET}`);
  const months = Object.keys(a).filter((k) => !isAgg(k)).map(monthOf);
  const odd = months.filter((m) => !/^\d{4}-\d{2}$/.test(m));
  if (growOn && odd.length) {
    console.error(`FACTS INVALID: ${file} - месяц не в формате YYYY-MM (${[...new Set(odd)].slice(0, 3).join(", ")}): без него нельзя отличить текущий месяц от закрытого, и потолок роста снялся бы молча. Проверь --month-key и формат даты в продьюсере.`);
    process.exit(1);
  }
  const newest = months.sort().pop() || "";
  const bad: string[] = [];
  for (const [mth, p] of Object.entries(a)) {
    const c = b[mth] || { n: 0, s: 0, k: {} };
    if (c.n < p.n * (1 - DROP)) bad.push(`${mth}: строк было ${p.n}, стало ${c.n} (потеря)`);
    else if (sumK && Math.abs(p.s) > 1 && Math.abs(c.s) < Math.abs(p.s) * (1 - DROP)) bad.push(`${mth}: сумма ${sumK} была ${Math.round(p.s)}, стала ${Math.round(c.s)} (потеря)`);
    // Гейт был односторонним и пропускал ЗАДВОЕНИЕ - а именно оно и грозило реализации: разбор
    // складывает поверх накопленного, и второй проход по той же паре удваивает месяц.
    // Файл без ключа кабинета (реализация): повторный разбор сливается по SKU и НЕ меняет число
    // строк, а законный добор УПД приносит новые SKU и число строк растит. Это и есть разделитель.
    // Убрав детектор целиком, я снял обнаружение ровно с того файла, где задвоение случалось трижды.
    else if (!growOn && sumK && c.n === p.n && Math.abs(p.s) > 1 && Math.abs(c.s) >= Math.abs(p.s) * (1 + GROW)) {
      bad.push(`${mth}: сумма ${sumK} была ${Math.round(p.s)}, стала ${Math.round(c.s)} при неизменном числе строк ${c.n} - это задвоение, а не добор (добор растит число строк)`);
    }
    else if (!growOn || isAgg(mth) || monthOf(mth) >= newest) continue; // текущий месяц ещё набирается - потолок роста не про него
    else if (BACKFILL_BELOW && monthOf(mth) < BACKFILL_BELOW) continue;  // месяц собирается впервые: см. backfillBelow
    else if (newKey && (c.n >= p.n * (1 + GROW) || (sumK && Math.abs(p.s) > 1 && Math.abs(c.s) >= Math.abs(p.s) * (1 + GROW)))) {
      const why = growByKeys(mth, p, c); if (why) bad.push(why);
    }
    else if (c.n >= p.n * (1 + GROW)) bad.push(`${mth}: строк было ${p.n}, стало ${c.n} (закрытый месяц вырос на ${Math.round((c.n / p.n - 1) * 100)}% - похоже на задвоение)`);
    else if (sumK && Math.abs(p.s) > 1 && Math.abs(c.s) >= Math.abs(p.s) * (1 + GROW)) bad.push(`${mth}: сумма ${sumK} была ${Math.round(p.s)}, стала ${Math.round(c.s)} (закрытый месяц вырос на ${Math.round((Math.abs(c.s) / Math.abs(p.s) - 1) * 100)}% - похоже на задвоение)`);
  }
  if (bad.length) {
    console.error(`FACTS INVALID: ${file} - аномалия по месяцам (порог потери ${Math.round(DROP * 100)}%, роста ${Math.round(GROW * 100)}%):\n  ${bad.join("\n  ")}`);
    console.error("Накопительный файл не имеет права ни терять собранный месяц, ни скачкообразно расти. Потеря - проверь ключ чистки в продьюсере (он обязан совпадать с ключом возобновляемости). Рост - проверь, не складывается ли разбор поверх уже накопленного.");
    process.exit(1);
  }
  console.log(`facts-gate ${file}: строк ${prev.length} -> ${cur.length}, месяцев ${Object.keys(a).length} -> ${Object.keys(b).length}, аномалий нет`);
}
main();
