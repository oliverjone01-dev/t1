import { describe, it, expect } from "vitest";
import { parseAttributionCsv } from "./parse-attribution.js";

// Реальный формат из probe-прогона (кампания 24324877).
const CSV = [
  ";Кампания по продвижению товаров № 24324877, период 26.05.2026-25.06.2026",
  "sku;Название товара;Цена товара, ₽;Показы;Клики;CTR, %;Добавления в корзину;Средняя стоимость клика, ₽;Расход, ₽, с НДС;Продано товаров;Продажи в продвижении, ₽;Продано товаров модели;Продажи в продвижении с заказов модели, ₽;ДРР в продвижении, %;Заказано на сумму, ₽;ДРР (общий), %;Дата добавления",
  "3564827172;GENGLASS Стол обеденный кухонный TRUBIS Wood 140х80 см;58660,00;151213;6277;4,15;269;14,53;91233,47;4;229600,00;10;581795,00;11,2;404300,00;22,6;02.04.2026",
  "Всего;;;151213;6277;4,15;269;14,53;91233,47;4;229600,00;10;581795,00;11,2;404300,00;22,6;",
].join("\n");

describe("parseAttributionCsv", () => {
  it("разбирает основную карточку и модель (объединённая = модель - основная)", () => {
    const rows = parseAttributionCsv(CSV);
    expect(rows).toHaveLength(1); // строка «Всего» пропущена
    expect(rows[0]).toEqual({
      sku: "3564827172",
      name: "GENGLASS Стол обеденный кухонный TRUBIS Wood 140х80 см",
      sp: 91233, sold: 4, om: 229600, soldModel: 10, omModel: 581795, drr: 11.2,
    });
    // объединённая (др. SKU) выводится фронтом как модель - основная
    expect(rows[0]!.omModel - rows[0]!.om).toBe(352195);
    expect(rows[0]!.soldModel - rows[0]!.sold).toBe(6);
  });

  it("пустой/мусорный отчёт -> []", () => {
    expect(parseAttributionCsv("")).toEqual([]);
    expect(parseAttributionCsv("нет данных")).toEqual([]);
  });
});
