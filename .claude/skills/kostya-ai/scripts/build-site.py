# ---------------------------------------------------------------- сборка данных
def name_key(s):
    """Ключ менеджера, устойчивый к порядку слов и к ё.

    Выгрузка диалогов даёт «Петрова Мария», rop.json даёт «Мария Петрова».
    Без нормализации слои A и B не соединяются: flagsByMgr оказывается пустым
    у всех, и 1540 флагов дисциплины не доезжают до карточки менеджера.
    """
    s = (s or "").lower().replace("ё", "е")
    parts = sorted(p for p in re.split(r"[^а-яa-z-]+", s) if len(p) > 1)
    return " ".join(parts)


def build_deal_index(msgs_path):
    """Детализация по сделкам: хронология, объёмы, реакции."""
    deals = defaultdict(lambda: {"msgs": [], "mgr": None, "stage": None, "amount": 0.0,
                                 "item": None, "client": None})
    with open(msgs_path, encoding="utf-8") as fh:
        for line in fh:
            m = json.loads(line)
            if m["kind"] != "msg" or m["sysmsg"] or not m["ts"]:
                continue
            d = deals[m["dealId"]]
            d["mgr"] = m["mgr"]
            d["stage"] = m["stage"]
            d["amount"] = max(d["amount"], m["amount"] or 0)
            d["item"] = m["itemType"]
            d["client"] = m["clientType"]
            d["msgs"].append(m)
    out = {}
    for did, d in deals.items():
        seq = sorted(d["msgs"], key=lambda x: x["ts"])
        ins = [x for x in seq if x["direction"] == "in"]
        outs = [x for x in seq if x["direction"] == "out"]
        out[did] = {
            "mgr": d["mgr"], "stage": d["stage"], "amount": d["amount"],
            "item": d["item"], "client": d["client"],
            "n": len(seq), "in": len(ins), "out": len(outs),
            "first": seq[0]["ts"], "last": seq[-1]["ts"],
            "lastDir": seq[-1]["direction"],
            "days": (datetime.fromisoformat(seq[-1]["ts"]) - datetime.fromisoformat(seq[0]["ts"])).days,
        }
    return out


def main(analysis_path, msgs_path, out_path, kostya_path=None):
    A = json.load(open(analysis_path, encoding="utf-8"))
    deals = build_deal_index(msgs_path)
    K = json.load(open(kostya_path, encoding="utf-8")) if kostya_path else None

    mgr_deals = defaultdict(list)
    for did, d in deals.items():
        mgr_deals[d["mgr"]].append((did, d))
    for v in mgr_deals.values():
        v.sort(key=lambda x: -x[1]["amount"])

    # Слой A (снимок Bitrix) индексируется по нормализованному ключу, потому что
    # имена там в обратном порядке относительно выгрузки диалогов.
    flags_by_key = defaultdict(list)
    kostya_by_key = {}
    if K:
        for f in K["flags"]:
            flags_by_key[name_key(f["mgr"])].append(f)
        for m in K["managers"]:
            kostya_by_key[name_key(m["mgr"])] = m

    # Ростер: только те, у кого есть заметный объём переписки.
    mgrs = [m for m in A["managers"] if m["out"] >= 25]

    joined = sum(1 for m in mgrs if kostya_by_key.get(name_key(m["mgr"])))
    print(f"join слоёв A и B: сведено {joined} из {len(mgrs)} менеджеров")
    if K and joined == 0:
        raise SystemExit("Слои A и B не сведены ни по одному менеджеру. Проверьте name_key и источники.")

    payload = {
        "meta": A["meta"], "totals": A["totals"],
        "managers": mgrs,
        "dealsByMgr": {m["mgr"]: [{"id": did, **d} for did, d in mgr_deals.get(m["mgr"], [])][:60] for m in mgrs},
        "flagsByMgr": {m["mgr"]: flags_by_key.get(name_key(m["mgr"]), [])[:40] for m in mgrs},
        "kostyaMeta": K["meta"] if K else None,
        "kostyaTotals": K["totals"] if K else None,
        "kostyaManagers": {m["mgr"]: kostya_by_key[name_key(m["mgr"])]
                           for m in mgrs if name_key(m["mgr"]) in kostya_by_key},
        # Адрес кабинета каждого. Список «кто под каким адресом» существует только
        # внутри зашифрованной сводки: снаружи адреса не называют людей, а Ивану и
        # РОПу нужно знать, кому какую ссылку отдать.
        "cabinets": {m["mgr"]: "k-" + hashlib.sha1(name_key(m["mgr"]).encode("utf-8")).hexdigest()[:10] + ".html"
                     for m in mgrs},
        "scripts": SALES_SCRIPTS, "followups": FOLLOWUPS, "magnets": MAGNETS,
        # Иконки едут данными, а не разметкой: набор один на библиотеку, кабинеты
        # и сводку, и лежит он в shared/icons.json. Копия внутри шаблона разошлась
        # бы с остальными молча.
        "icons": ICONS,
    }

    tpl = open(__file__.replace("build-site.py", "site-template.html"), encoding="utf-8").read()
    htmlout = tpl.replace("/*__DATA__*/null", json.dumps(payload, ensure_ascii=False))

    if FRAGMENT:
        css = re.search(r"<style>([\s\S]*?)</style>", htmlout).group(1)
        body = re.search(r"<body>([\s\S]*?)</body>", htmlout).group(1)
        css_path = os.path.join(os.path.dirname(os.path.abspath(out_path)) or ".", "rop.css")
        open(css_path, "w", encoding="utf-8").write(scope_css(css))
        open(out_path, "w", encoding="utf-8").write('<div class="rop">' + body + "</div>")
        print(f"фрагмент сводки: {out_path} ({len(body)//1024} КБ), стили: {css_path}")
    else:
        open(out_path, "w", encoding="utf-8").write(htmlout)
        print(f"сайт: {out_path} ({len(htmlout)//1024} КБ), менеджеров {len(mgrs)}, сделок {len(deals)}")


if __name__ == "__main__":
    main(*sys.argv[1:5])
