const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

/**
 * Промт к картинке для генерации файлов из CLI (`--prompts`). На страницу он не
 * попадает: общая часть стиля лежит в одном месте, сцена в своём, а менеджеру
 * промт ничего не меняет.
 */
function situPrompt(s) {
  const st = SITU.prompt_style;
  if (!st || !Array.isArray(st.assembly)) {
    throw new Error("В situations.json нет prompt_style.assembly: промт не из чего собрать");
  }
  return st.assembly
    .map((k) => (k === "scene" ? s.scene : st[k]))
    .map((part) => String(part ?? "").trim())
    .filter(Boolean)
    .join(" ");
}

/**
 * Иллюстрация к типовой ситуации.
 *
 * Файл может отсутствовать, поэтому <img> подстраховывается вторым форматом, а
 * дальше рамкой с подписью. Промт к картинке на экран не выводится: это
 * внутренняя кухня генерации, менеджеру она ничего не меняет.
 */
function situ(id) {
  const s = (SITU.situations || []).find((x) => x.id === id);
  if (!s) throw new Error(`Нет ситуации ${id} в situations.json`);
  return `<figure class="situ" id="situ-${s.id}">
  <img src="img/${s.id}.svg" alt="${esc(s.alt)}"
       onerror="var f=this.closest('.situ');if(!this.dataset.f){this.dataset.f=1;this.src='img/${s.id}.webp'}else{f.classList.add('no-img')}">
  <div class="ph"><div class="ph-h">${ic("picture")}<b>${esc(s.title)}</b></div></div>
  <figcaption>${esc(s.title)}</figcaption>
</figure>`;
}

