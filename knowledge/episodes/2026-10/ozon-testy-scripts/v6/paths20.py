# v6: пути к «К выплате» 20 млн в месяц (запрос Ивана 14.10). Та же линейная модель «Отчета», что forecast30.py:
# доли структуры - из листа «Допущения» книги прогноза (средняя = июль-сентябрь, сент. = сентябрь), числа ниже - их копия.
# Запуск: python3 -I paths20.py
S = {'средн': dict(comm=.4779, logi=.0142, acq=.0064, sto=.0005, oth=.0367, cpo=.0498, clk=.046, cc=.1705, dinc=2456, ship=2508, real=.4488, badm=.0371),
     'сент': dict(comm=.4951, logi=.0084, acq=.0064, sto=.0001, oth=.0308, cpo=.0389, clk=.039, cc=.1574, dinc=3046, ship=2925, real=.4389, badm=.0268)}
N0, U0, P0 = 21010545, 271, 77529.7          # сентябрь «Отчета»: оборот, шт, оборот на 1 шт
CLK_ITEM, U_MID, U_HIGH, P_CLK = 1500 * 4.35, 1.39, 2.78, 57000     # тест 1: расход на товар в месяц, шт на товар (средн./верх), цена
MIR_P = 56172                                                          # зеркало: оборот на 1 шт, сентябрь
P_SPR = (14634289 + 24900676 + 22407965 + 25842075) / (369 + 581 + 432 + 494)   # март-июнь: оборот на 1 шт (больше зеркал)

def pl(s, N, u, click):
    kv = N * (1 - s['comm'] - s['logi'] - s['acq'] - s['sto'] - s['oth'] - s['cpo']) - click
    ad = N * s['cpo'] + click
    net = kv - s['cc'] * N - (s['ship'] - s['dinc']) * u - 0.3 * (kv + 0.86 * ad + s['badm'] * N) - 0.15 * s['real'] * N
    return kv, net, ad / N

PATHS = {
    '0 сейчас': (0, 0, 0),
    '1 весна 581 шт': (310, 310 * P0, 0),
    '1а весна 469 шт': (198, 198 * P0, 0),
    '1б весна 581 шт по цене штуки весны': (310, 581 * P_SPR - N0, 0),
    '2 клик 300 товаров (средн.)': (300 * U_MID, 300 * U_MID * P_CLK, 300 * CLK_ITEM),
    '2в клик 300 товаров (верх)': (300 * U_HIGH, 300 * U_HIGH * P_CLK, 300 * CLK_ITEM),
    '3 зеркала к июню (+113)': (113, 113 * MIR_P, 0),
    '4 срезать дорогой клик 0,4 млн': (0, 0, -400000),
    'А: 1 + клик 100 + срез 0,3': (310 + 100 * U_MID, 310 * P0 + 100 * U_MID * P_CLK, 100 * CLK_ITEM - 300000),
    'Б: 1а + клик 300 + срез 0,3': (198 + 300 * U_MID, 198 * P0 + 300 * U_MID * P_CLK, 300 * CLK_ITEM - 300000),
    'А2: 1б + клик 100 + срез 0,3': (310 + 100 * U_MID, 581 * P_SPR - N0 + 100 * U_MID * P_CLK, 100 * CLK_ITEM - 300000),
    'В: клик 400 (верх) + срез 0,3': (400 * U_HIGH, 400 * U_HIGH * P_CLK, 400 * CLK_ITEM - 300000),
    'без пути 1: клик 100 + зеркала + срез 0,3': (100 * U_MID + 113, 100 * U_MID * P_CLK + 113 * MIR_P, 100 * CLK_ITEM - 300000),
}
for name, (du, dN, dc) in PATHS.items():
    row = []
    for k, s in S.items():
        kv, net, ads = pl(s, N0 + dN, U0 + du, s['clk'] * N0 + dc)
        row.append(f'{k}: КВ {kv / 1e6:.1f} чистая {net / 1e6:+.2f} реклама {ads * 100:.1f}%')
    print(f'{name:45s} оборот {(N0 + dN) / 1e6:5.1f} шт {U0 + du:5.0f} | ' + ' | '.join(row))
print('оборот на 1 шт март-июнь', round(P_SPR))
for R in (1.24, 2.56, 2.85):
    print('клик с отдачей', R, '₽/₽: «К выплате» на 1 ₽ =', {k: round(R * (1 - s['comm'] - s['logi'] - s['acq'] - s['sto'] - s['oth'] - s['cpo']) - 1, 2) for k, s in S.items()})
