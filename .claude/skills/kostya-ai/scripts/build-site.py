def scope_css(css, scope=".rop"):
    """Ограничивает стили сводки её собственным контейнером.

    Сводка уезжает разделом внутрь академии, а её CSS написан по тегам: main,
    header, table, h2, body. Подключается он позже общего, поэтому без
    ограничения переопределил бы каркас академии целиком. Разбор идёт по
    скобкам, а не регуляркой: внутри @media лежат вложенные блоки.
    """
    res, i, n = [], 0, len(css)
    while i < n:
        if css.startswith("/*", i):
            j = css.find("*/", i + 2)
            j = n if j < 0 else j + 2
            res.append(css[i:j])
            i = j
            continue
        j = css.find("{", i)
        if j < 0:
            res.append(css[i:])
            break
        sel = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if sel.startswith("@"):
            inner = scope_css(body, scope) if sel.startswith(("@media", "@supports")) else body
            res.append(sel + "{" + inner + "}")
        else:
            parts = []
            for one in (x.strip() for x in sel.split(",")):
                if not one:
                    continue
                if one == "*":
                    parts.append(scope + " *")
                elif one in (":root", "html"):
                    parts.append(scope)
                elif one == "body":
                    parts.append(scope)
                elif one.startswith("body"):
                    parts.append(scope + one[4:])
                else:
                    parts.append(scope + " " + one)
            res.append(", ".join(parts) + "{" + body + "}")
        i = k
    return "".join(res)


def esc(s):
    return html.escape(str(s if s is not None else ""))

def fmt_min(v):
    if v is None:
        return "нет данных"
    v = int(v)
    if v < 60:
        return f"{v} мин"
    if v < 60 * 8:
        return f"{v // 60} ч {v % 60:02d} м"
    return f"{v / 60 / 8:.1f} раб. дн."

def money(n):
    return f"{int(n or 0):,}".replace(",", " ") + " ₽"

def pctf(v, digits=0):
    return "нет данных" if v is None else f"{v * 100:.{digits}f}%"


