// Минимально различимая разница по редким событиям (заказам).
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. 24.09 ФЕНИКС поймал в этом расчёте ошибку, которая молча печаталась
// на публикуемой странице: стандартная ошибка считалась верно, а результат выводился не в той
// шкале. Теперь математика лежит отдельно и покрыта тестами, а страница только печатает.
//
// ЧТО СЧИТАЕТСЯ. Разность разностей по счётным событиям: сравниваются приросты тестовой и
// контрольной групп. По Пуассону дисперсия логарифма числа событий приближается как 1/k
// (дельта-метод), поэтому стандартная ошибка ЛОГАРИФМА отношения приростов это корень из
// суммы 1/k по всем четырём окнам: база теста, окно теста, база контроля, окно контроля.
//
// ГЛАВНОЕ: 2.8 × SE ЭТО ЛОГАРИФМ, А НЕ ПРОЦЕНТЫ. Печатать его как проценты можно только при
// малых значениях, когда ln(1+x) ≈ x. При SE около единицы это враньё: 2.8 × SE = 2.88 давало
// «288 %», хотя настоящие пороги это рост в 17.8 раза и падение на 94.4 %. Падения на 288 %
// не бывает вовсе, а критерий теста как раз про падение. Поэтому наружу отдаются два конца в
// относительных единицах, а не одно симметричное число.
//
// ПОЧЕМУ ПОРОГИ НЕСИММЕТРИЧНЫ. Шкала логарифмическая: вниз она упирается в -100 %, вверх не
// ограничена. Одна и та же величина в логарифмах это -94.4 % вниз и +1676 % вверх.

/** 1.96 + 0.84: 80 % мощности при 5 % двустороннем. */
export const Z_POWER = 2.8;

export interface Counts {
  /** События тестовой группы в базовом окне. */
  kTb: number;
  /** Ожидаемые события тестовой группы в окне замера. */
  kTp: number;
  /** События контрольной группы в базовом окне. */
  kCb: number;
  /** Ожидаемые события контрольной группы в окне замера. */
  kCp: number;
}

/** Стандартная ошибка логарифма отношения приростов. null - хотя бы одно окно пустое. */
export function seLog(c: Counts): number | null {
  const ks = [c.kTb, c.kTp, c.kCb, c.kCp];
  if (ks.some((k) => !(k > 0))) return null;
  return Math.sqrt(ks.reduce((s, k) => s + 1 / k, 0));
}

export interface Detectable {
  /** Минимально различимое падение, в процентах и со знаком минус. Ближе к -100 - хуже. */
  drop: number;
  /** Минимально различимый рост, в процентах. */
  rise: number;
  /** Порог в логарифмах, из которого получены оба конца. */
  log: number;
}

/** Два конца порога в относительных единицах. */
export function detectable(se: number, z = Z_POWER): Detectable {
  const log = z * se;
  return { drop: (Math.exp(-log) - 1) * 100, rise: (Math.exp(log) - 1) * 100, log };
}

/** Сколько событий нужно в КАЖДОМ из четырёх окон, чтобы различить падение на rel процентов.
 *
 *  Падение на 100 % это ноль событий, его логарифм не определён, и «различить» его нельзя
 *  никаким объёмом данных. Такой запрос возвращает null, а не большое число: строка «чтобы
 *  различить двукратное падение, нужно 16 заказов» была бессмысленной именно из-за этого. */
export function ordersNeeded(rel: number, z = Z_POWER): number | null {
  if (!(rel > 0) || rel >= 100) return null;
  const L = Math.abs(Math.log(1 - rel / 100));
  return Math.ceil(4 * (z / L) ** 2);
}
