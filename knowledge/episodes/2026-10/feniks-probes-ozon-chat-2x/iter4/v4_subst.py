# Выводимые артикулы ещё продаются (v4_base.py: 4 заказа за 12-14.10 против 25 за 28 дней базы). Когда они кончатся,
# часть их спроса может уйти на соседние товары той же объединённой карточки (замещение s). Тогда остаток карточки
# растёт без эффекта клика и цены, и порог v3 пропускает «без эффекта» чаще 15%. Считаю P(пройти без эффекта)
# при s = 0 / 25 / 50 / 100% и прирост, нужный для 50% шанса (как таблица iter3). Числа базы - v4_base.py.
# python3 -I v4_subst.py
import math

# карточка, база всего, от выводимых, порог v2, порог v3
CARDS = [('KUVINO', 30, 4, 20, 18), ('EVELIX', 21, 5, 15, 12), ('OSOLIS', 17, 5, 13, 10), ('ARFEO', 11, 6, 9, 5), ('ARKIS', 10, 5, 8, 5)]


def p_ge(lam, k):
    pmf, cdf = math.exp(-lam), 0.0
    for i in range(k):
        cdf += pmf; pmf *= lam / (i + 1)
    return 1 - cdf


def need(lam, k):
    lo, hi = 0.0, 50.0
    for _ in range(80):
        m = (lo + hi) / 2
        lo, hi = (m, hi) if p_ge(lam * m, k) < 0.5 else (lo, m)
    return hi


print('карточка | база без выв. / выв. | порог v3 | P(пройти без эффекта) при замещении 0 / 25 / 50 / 100% | прирост для 50%: v3 (s=0) / iter3 v2 при выводимых = 0')
exp_false = {s: 0.0 for s in (0, 0.25, 0.5, 1)}
for name, b, o, t2, t3 in CARDS:
    rest, out = (b - o) / 2, o / 2
    ps = {s: p_ge(rest + s * out, t3) for s in exp_false}
    for s in ps:
        exp_false[s] += ps[s]
    print(f'{name} | {b - o} / {o} | {t3} | ' + ' / '.join(f'{ps[s]:.1%}' for s in ps)
          + f' | +{need(rest, t3) - 1:.0%} / +{need(rest, t2) - 1:.0%}')
print('ожидаемое число ложно оставленных из 5 при нулевом эффекте:', ' / '.join(f'{v:.2f}' for v in exp_false.values()))
