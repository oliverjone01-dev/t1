    # имена там в обратном порядке относительно выгрузки диалогов.
    flags_by_key = defaultdict(list)
    kostya_by_key = {}
    if K:
        for f in K["flags"]:
            flags_by_key[name_key(f["mgr"])].append(f)
        for m in K["managers"]:
            kostya_by_key[name_key(m["mgr"])] = m

