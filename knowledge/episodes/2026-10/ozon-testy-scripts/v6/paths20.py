# v6: пути к «К выплате» 20 млн в месяц (запрос Ивана 14.10). Та же линейная модель «Отчета», что forecast30.py:
# доли структуры - из листа «Допущения» книги прогноза (средняя = июль-сентябрь, сент. = сентябрь), числа ниже - их копия.
# Итерация 2 (предпроверка ФЕНИКСА, return без скоринга, F1-F8): весенние штуки - и с весенним кликом; себестоимость
# штуки весны; путь 2 и вариант В - три оценки (x0,3 / средняя / верх); срез дорогого клика по текущему темпу.
# Запуск: python3 -I paths20.py
S = {'средн': dict(comm=.4779, logi=.0142, acq=.0064, sto=.0005, oth=.0367, cpo=.0498, clk=.046, cc=.1705, dinc=2456, ship=2508, real=.4488, badm=.0371),
     'сент': dict(comm=.4951, logi=.0084, acq=.0064, sto=.0001, oth=.0308, cpo=.0389, clk=.039, cc=.1574, dinc=3046, ship=2925, real=.4389, badm=.0268)}
N0, U0, P0 = 21010545, 271, 77529.7          # сентябрь «Отчета»: оборот, шт, оборот на 1 шт
CLK_ITEM, P_CLK = 1500 * 4.35, 57000         # тест 1: расход на товар в месяц, цена тестовых товаров
U2 = {'x0,3': 2.78 * 0.3, 'средн': 1.39, 'верх': 2.78}   # тест 1: шт на товар в месяц (верх = 2,1 шт за 23 дня, осторожный счёт)
MIR_P = 56172                                # зеркало: оборот на 1 шт, сентябрь
# март-июнь «Отчета» (блоки 1, 3, 4): оборот, шт, себестоимость, клик
N_SPR = 14634289 + 24900676 + 22407965 + 25842075
U_SPR = 369 + 581 + 432 + 494
P_SPR = N_SPR / U_SPR                                          # 46 794 ₽ на шт (больше зеркал)
CC_SPR = (3307293 + 5904045 + 4978908 + 5308149) / U_SPR       # 10 393 ₽ себестоимости на шт
CLK_SPR = (1799552 + 2291580 + 1913006 + 1397032) / 4          # 1,85 млн клика в месяц весной
CUT = {'без KUVINO': 250000, 'с KUVINO': 330000}               # срез дорогого клика по темпу 01-11.10 (проба ФЕНИКСА p_campaigns)

def pl(s, N, u, click, cc_abs=None):
    """«К выплате», чистая «Отчета», реклама / оборот. cc_abs - себестоимость в рублях (иначе доля от оборота)"""
    kv = N * (1 - s['comm'] - s['logi'] - s['acq'] - s['sto'] - s['oth'] - s['cpo']) - click
    ad = N * s['cpo'] + click
    cc = s['cc'] * N if cc_abs is None else cc_abs
    net = kv - cc - (s['ship'] - s['dinc']) * u - 0.3 * (kv + 0.86 * ad + s['badm'] * N) - 0.15 * s['real'] * N
    return kv, net, ad / N

def row(name, du, dN, dclk, spr_clk=False, cc_spr=False):
    out = []
    for k, s in S.items():
        base_clk = s['clk'] * N0
        click = (CLK_SPR if spr_clk else base_clk) + dclk
        cc = CC_SPR * (U0 + du) if cc_spr else None
        kv, net, ads = pl(s, N0 + dN, U0 + du, click, cc)
        out.append(f'{k}: КВ {kv / 1e6:.1f} чистая {net / 1e6:+.2f} реклама {ads * 100:.1f}%')
    print(f'{name:58s} оборот {(N0 + dN) / 1e6:5.1f} шт {U0 + du:5.0f} | ' + ' | '.join(out))

D1, D1a, D1b = 310, 198, 310
print('--- пути')
row('0 сейчас', 0, 0, 0)
row('1 весна 581 шт, цена сентября, клик как сейчас', D1, D1 * P0, 0)
row('1 весна 581 шт, цена сентября, клик весны', D1, D1 * P0, 0, spr_clk=True)
row('1а весна 469 шт, цена сентября, клик как сейчас', D1a, D1a * P0, 0)
row('1а весна 469 шт, цена сентября, клик весны', D1a, D1a * P0, 0, spr_clk=True)
row('1б весна 581 шт по цене и себестоимости весны, клик весны', D1b, 581 * P_SPR - N0, 0, spr_clk=True, cc_spr=True)
for k, u in U2.items():
    row(f'2 дешёвый клик 300 товаров ({k})', 300 * u, 300 * u * P_CLK, 300 * CLK_ITEM)
row('3 зеркала к июню (+113)', 113, 113 * MIR_P, 0)
for k, v in CUT.items():
    row(f'4 срез дорогого клика {k} ({v / 1e3:.0f} тыс.)', 0, 0, -v)
print('--- комбинации')
row('А: 1 (581, цена сент.) + клик 100 средн + срез 0,25; клик как сейчас', D1 + 100 * U2['средн'], D1 * P0 + 100 * U2['средн'] * P_CLK, 100 * CLK_ITEM - CUT['без KUVINO'])
row('А: то же, клик весны', D1 + 100 * U2['средн'], D1 * P0 + 100 * U2['средн'] * P_CLK, 100 * CLK_ITEM - CUT['без KUVINO'], spr_clk=True)
row('А2: 1б + клик 100 средн + срез 0,25 (себест. весны)', D1b + 100 * U2['средн'], 581 * P_SPR - N0 + 100 * U2['средн'] * P_CLK, 100 * CLK_ITEM - CUT['без KUVINO'], spr_clk=True, cc_spr=True)
for k, u in U2.items():
    row(f'В: клик 400 товаров ({k}) + срез 0,25', 400 * u, 400 * u * P_CLK, 400 * CLK_ITEM - CUT['без KUVINO'])
row('без пути 1: клик 100 средн + зеркала + срез 0,25', 100 * U2['средн'] + 113, 100 * U2['средн'] * P_CLK + 113 * MIR_P, 100 * CLK_ITEM - CUT['без KUVINO'])
print('--- механика клика: «К выплате» на 1 ₽ клика = R × m − 1')
for k, s in S.items():
    m = 1 - s['comm'] - s['logi'] - s['acq'] - s['sto'] - s['oth'] - s['cpo']
    print(k, 'm', round(m, 4), 'порог R', round(1 / m, 2), {R: round(R * m - 1, 2) for R in (1.24, 2.56, 2.85)})
print('весна: оборот на шт', round(P_SPR), 'себестоимость на шт', round(CC_SPR), 'клик в месяц', round(CLK_SPR))
