let dom: JSDOM;
const errs: string[] = [];

const num = (s: string | null | undefined): number | null => {
  const v = parseFloat(String(s ?? "").replace(/[^\d,.-]/g, "").replace(/ |\s/g, "").replace(",", "."));
  return isNaN(v) ? null : v;
};

