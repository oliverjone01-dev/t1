import { kuratorAudit, workMinutes } from "./pamyatka-rules";

const T0 = new Date("2026-08-25T11:00:00+03:00").getTime(); // рабочее утро
const ev = (min: number, dir: string, body: string, who = "Продавцова Анна", dealId = "1") => ({
  ts: String(T0 + min * 6e4), dt: new Date(T0 + min * 6e4).toISOString().replace("Z", "+03:00").slice(0, 19) + "+03:00",
  dealId, leadId: "", dir, who, body, mgr: "Продавцова Анна",
});
const dlg = {
  from: "2026-08-23T00:00:00+03:00", to: "2026-08-30T23:59:59+03:00",
  events: [
    // сделка 1: клиент пишет, продавец отвечает через 40 РАБОЧИХ минут -> R1-улика, fr=1, frOk=0
    ev(0, "входящее", "Здравствуйте, посчитайте перегородку", "Клиент"),
    ev(40, "исходящее", "Добрый день! Посчитаю и пришлю расчёт", "Продавцова Анна"), // и R2: обещание без даты
    // маркер вложения без текста рядом -> R3 (одна улика, батч минуты)
    ev(60, "исходящее", "Отправлено Файл", "Продавцова Анна"),
    ev(60.5, "исходящее", "Отправлено Изображение", "Продавцова Анна"),
    // «в ближайшее время» без обещания-глагола в том же предложении -> R5
    ev(90, "исходящее", "Ответ будет в ближайшее время", "Продавцова Анна"),
    // сделка 2: маркер вложения НЕ считается обещанием; «уточните» (просьба) не обещание;
    // вежливая формула не обещание; обещание С датой -> prOk
    ev(0, "входящее", "Добрый день", "Клиент", "2"),
    ev(5, "исходящее", "Добрый день! С радостью отвечу на вопросы", "Продавцова Анна", "2"),
    ev(6, "исходящее", "Уточните, пожалуйста, размеры", "Продавцова Анна", "2"),
    ev(7, "исходящее", "Пришлю расчёт завтра до 12:00", "Продавцова Анна", "2"),
    ev(8, "исходящее", "Отправлено Файл", "Продавцова Анна", "2"),
    ev(9, "исходящее", "Направляю КП по вашему запросу, посмотрите пожалуйста", "Продавцова Анна", "2"),
    // сделка 3: письмо-тред с «руководителем» в цитате -> НЕ эскалация; звонок не «клиент написал»
    ev(0, "входящее", "Звонок входящий, 0:45", "Клиент", "3"),
    ev(10, "входящее", "Тема: Re: запрос\nНаш руководитель просил уточнить смету, цитирую переписку ниже", "Клиент", "3"),
    ev(20, "исходящее", "Смету уточню и пришлю сегодня до 18:00", "Продавцова Анна", "3"),
    // сделка 4: ответ писал ОФИСНЫЙ сотрудник -> продавцу не атрибутируется, идёт в первую линию
    ev(0, "входящее", "Посчитайте стол", "Клиент", "4"),
    ev(200, "исходящее", "Передала менеджеру, посчитает и пришлёт", "Офисова Ольга", "4"),
    // событие ВНЕ окна -> не считается вовсе
    { ts: String(new Date("2026-06-01T12:00:00+03:00").getTime()), dt: "2026-06-01T12:00:00+03:00", dealId: "5", leadId: "", dir: "исходящее", who: "Продавцова Анна", body: "Пришлю расчёт когда-нибудь", mgr: "Продавцова Анна" },
  ],
};
const lookup = (k: string) => ({ dealId: k.slice(1), isLead: 0, mgr: "Продавцова Анна", title: "Тест " + k, budget: 100000 });
const isSeller = (n: string) => n === "Продавцова Анна";
const K = kuratorAudit(dlg as any, lookup, (s) => s, isSeller);

let fails = 0;
const ck = (name: string, ok: boolean, info = "") => { if (ok) console.log("OK  ", name); else { fails++; console.log("FAIL", name, info); } };
const A = K.mgrs["Продавцова Анна"] || ({} as any);
const allV = (A.deals || []).flatMap((d: any) => d.viol.map((v: any) => v.r + "|" + v.q));
ck("R1: 40 рабочих минут - улика есть", allV.some((v: string) => v.startsWith("R1|")));
ck("R1: рабочие минуты в формулировке", allV.some((v: string) => v.startsWith("R1|") && v.includes("рабочего времени")));
ck("R2: «посчитаю и пришлю» без даты - улика", allV.some((v: string) => v.startsWith("R2|") && v.includes("Посчитаю и пришлю")));
ck("R2: маркер вложения НЕ обещание", !allV.some((v: string) => v.startsWith("R2|") && v.includes("Отправлено")));
ck("R2: «уточните» (просьба клиенту) не обещание", !allV.some((v: string) => v.includes("Уточните")));
ck("R2: вежливая формула не обещание", !allV.some((v: string) => v.includes("С радостью")));
ck("R2: «направляю» (уже сделанное) не обещание", !allV.some((v: string) => v.includes("Направляю КП")));
ck("R2: обещание с датой прошло в prOk", A.prOk >= 2, "prOk=" + A.prOk);
ck("R3: батч вложений минуты = одна улика", allV.filter((v: string) => v.startsWith("R3|")).length === 1, JSON.stringify(allV.filter((v: string) => v.startsWith("R3|"))));
ck("R3: вложение с текстом-соседом (сделка 2) не улика", !allV.some((v: string) => v.startsWith("R3|") && v.includes("Тест d2")));
ck("R5: «в ближайшее время» - улика", allV.some((v: string) => v.startsWith("R5|")));
ck("R9: «руководитель» в письме-треде НЕ эскалация", !allV.some((v: string) => v.startsWith("R9|")));
ck("Звонок и письмо-тред не считаются «клиент написал» (сделка 3 пары не даёт)", A.fr === 2, "fr=" + A.fr);
ck("Офисный автор: улика НЕ у продавца, пара в первой линии", K.firstLine.fr === 1 && !allV.some((v: string) => v.includes("Передала менеджеру")), "flFr=" + K.firstLine.fr);
ck("Событие вне окна не считается", !allV.some((v: string) => v.includes("когда-нибудь")));
ck("workMinutes: ночь не считается", workMinutes(new Date("2026-08-25T17:50:00+03:00").getTime(), new Date("2026-08-26T09:10:00+03:00").getTime()) <= 25, String(workMinutes(new Date("2026-08-25T17:50:00+03:00").getTime(), new Date("2026-08-26T09:10:00+03:00").getTime())));

if (fails) { console.error("PAMYATKA-RULES TEST: " + fails + " FAIL"); process.exit(1); }
console.log("PAMYATKA-RULES TEST PASS: " + (16 - fails) + "/16");
