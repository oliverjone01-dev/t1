// Кириллические двойники в кодах артикулов. Маркет отдаёт часть артикулов с русскими буквами,
// визуально неотличимыми от латинских: «GGМ-16-4-3» (русская М) и «GGTP-20-2х2» (русская х).
// В листе себестоимости такие коды не встречаются ни разу, поэтому прямой ключ по ним не
// срабатывал никогда, и артикул молча оставался без С\С. Нормализация приводит код к латинице.
// Заменяем ТОЛЬКО буквы, у которых есть латинский двойник той же формы: иначе можно склеить
// два разных артикула. На живых данных (417 строк листа, 1008 строк свода) коллизий нет.
const PAIRS: Record<string, string> = {
  "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O", "Р": "P", "С": "C",
  "Т": "T", "Х": "X", "У": "Y", "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "х": "x", "у": "y",
};
export function normSku(sku: string): string {
  return String(sku || "").replace(/[АВЕКМНОРСТХУаеорсху]/g, (c) => PAIRS[c] || c);
}
