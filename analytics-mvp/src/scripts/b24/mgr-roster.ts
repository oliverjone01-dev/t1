import { readFileSync } from "node:fs";
// Кто считается продавцом отдела. Один список на все скрипты диалогов: скоринг
// (score-dialog.ts) и выгрузка очереди на разбор (dump-dialogs.ts) должны смотреть
// на одних и тех же людей, иначе в разбор уходят те, кого дашборд не показывает.
//
// EXCLUDE_MGR - явно названные Иваном не-наши: числятся в CRM, но продажами C49 не занимаются.
// KEEP_MGR - исключения из списка уволенных: числится уволенным в CRM, но работает.
// Лобова: в портале два пользователя с этим ФИО. ID 7999 - рабочая (активна, вход
// ежедневно, 15 сделок C49, 60 активностей), ID 8001 - ошибочный дубль (отключена,
// ноль сделок). В firedManagers попал дубль, поэтому по имени фильтр снёс бы живого
// человека. Проверено пробой 18.08.2026.
// Турченко Анна - офис-менеджер, ведёт первичную работу с лидами. В firedManagers
// попала ошибочно (в портале несколько учёток с этой фамилией), поэтому держим явно.
// Разбором коммуникаций не оценивается: у лид-интейка другая задача (роль office).
export const EXCLUDE_MGR = new Set(["Лысенко Ольга", "Сячинова Александра", "Мавлина Юлия", "Ерина Екатерина", "Королькова Наталья", "Павлова Анна"]);
export const KEEP_MGR = new Set(["Лобова Надежда", "Турченко Анна"]);
export const OFFICE_MGR = "Турченко Анна";

export const swapName = (n: string) => { const p = n.trim().split(/\s+/); return p.length === 2 ? p[1] + " " + p[0] : n; };

// Пусто - человек в отделе продаж. Иначе строка с причиной, почему он не показывается.
export function isHidden(mgr: string, fired: Set<string>): string {
  if (KEEP_MGR.has(mgr)) return "";
  if (/^Системный пользователь/i.test(mgr) || mgr === "(не указан)") return "робот портала";
  if (!/[A-Za-zА-Яа-яЁё]/.test(mgr)) return "ID без имени";
  if (EXCLUDE_MGR.has(mgr)) return "не в отделе продаж";
  if (fired.has(mgr) || fired.has(swapName(mgr))) return "уволен";
  return "";
}

// Список уволенных берём из снимка РОПа. Файла нет - работаем без него: скрипт разбора
// должен запускаться и на машине, где снимок не выгружен.
export function loadFired(path: string): Set<string> {
  try {
    const rop = JSON.parse(readFileSync(path, "utf8"));
    return new Set((rop.firedManagers || []) as string[]);
  } catch { return new Set<string>(); }
}
