def num(s):
    s = s.replace('−', '-').replace('\xa0', ' ').replace(' ', '').replace('₽', '').replace(',', '.')
    if s.endswith('%'): return float(s[:-1]) / 100
    return float(s) if re.fullmatch(r'[-+]?\d+(\.\d+)?', s) else None

def rows_of(txt, header_start, n):
    """строки таблицы, у которой заголовок начинается с header_start: {подпись: [n чисел]}"""
    out, on = {}, False
    for line in txt.splitlines():
        if line.startswith(header_start + '\t'): on = True; continue
        if on:
            parts = line.split('\t')
            if len(parts) < n + 1: break
            vals = [num(p) for p in parts[1:n + 1]]
            out[parts[0]] = vals
    return out

