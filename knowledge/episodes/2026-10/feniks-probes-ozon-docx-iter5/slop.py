"""C4/D1: Anti-Slop v2 (style.md §7) и самопровозглашённая оценка по тексту docx и разделу памятки."""
import re, sys
PATS = ['в мире современного дизайна', 'не секрет, что', 'на протяжении веков', 'является неотъемлемой частью',
        'позволяет создать', 'позволяет реализовать', 'уникальн', 'инновационн', 'революционн', 'непревзойд',
        'эксклюзивн', 'высокое качество', 'опытные специалисты', 'индивидуальный подход', 'доступные цены',
        'гармонично вписывается', 'идеальное решение', 'гармоничное сочетание', 'квинтэссенц', 'один из лучших',
        'премиум-сегмент', 'топовое предложение', 'удвоит', 'выстрелит', 'взорвёт', 'никто в рф не делает',
        'уникальный актив', 'просто надо подключить', 'база уже есть', 'выглядит хорошо', 'отлично подойдёт']
for p in sys.argv[1:]:
    t = open(p).read().lower()
    hits = [x for x in PATS if x in t]
    score = re.findall(r'\b\d{1,2}[.,]\d\s*/\s*10\b|оценка\s+\d', t)
    print(p.rsplit('/', 1)[-1], 'patterns', len(PATS), 'hits', hits, 'self-score', score)
